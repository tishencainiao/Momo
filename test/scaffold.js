#!/usr/bin/env node
/* P5 护栏测试：脚手架生成完整清单 + 进化层 selfModify 模板带完整清单 */
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
const NODE = process.execPath;
const SCAFFOLD = path.join(ROOT, "scripts", "scaffold-plugin.js");
const EVOLUTION = path.join(ROOT, "plugins", "evolution.js");

let pass = 0, fail = 0;
function check(name, cond, extra) {
  if (cond) { pass++; console.log("✓ " + name); }
  else { fail++; console.log("✗ " + name + (extra ? "  → " + extra : "")); }
}

// 1. 脚手架生成带完整清单的模板
const name = "test-scaffold-probe-" + Date.now().toString(36);
const target = path.join(ROOT, "plugins", name + ".js");
try {
  const r = spawnSync(NODE, [SCAFFOLD, name, "测试探针"], { encoding: "utf8" });
  check("脚手架正常退出", r.status === 0, "status=" + r.status);
  let src = "";
  if (fs.existsSync(target)) src = fs.readFileSync(target, "utf8");
  check("生成了模板文件", src.length > 0);
  for (const field of ["name:", "displayName:", "description:", "version:", "engines:", "permissions:", "init(ctx)", "attribution", "apiSpec", "requires:"]) {
    check("模板含字段 " + field, src.includes(field));
  }
  const km = src.match(/kernel:\s*"([^"]+)"/);
  check("engines.kernel 填当前内核版本", !!km && /^>=/.test(km[1]), km ? km[1] : "无");
} finally {
  try { fs.unlinkSync(target); } catch (e) {}
}

// 2. 坏名被拒绝
const bad = spawnSync(NODE, [SCAFFOLD, "BadName"], { encoding: "utf8" });
check("坏名被拒绝（kebab-case）", bad.status !== 0 && /kebab/.test(bad.stderr || ""));

// 3. 进化层 selfModify 生成模板带完整清单（静态检查源码）
const evo = fs.readFileSync(EVOLUTION, "utf8");
check("selfModify 模板带 attribution（self-generated）", evo.includes("self-generated by Momo"));
check("selfModify 模板带 engines.kernel", evo.includes('engines: { kernel: ">=${_ctx.BASE_VERSION}" }'));
check("selfModify 模板带 displayName+description+permissions",
  evo.includes("displayName:") && evo.includes("description:") && evo.includes("permissions:"));

console.log(`\n通过 ${pass} / 失败 ${fail}`);
process.exit(fail ? 1 : 0);
